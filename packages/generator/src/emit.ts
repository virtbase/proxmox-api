import type { PveCall, PveMethod, PveNode, PveSchema } from "./schema.js";
import { isOptional, pathVariable } from "./schema.js";

const INDENT = "  ";
const METHOD_ORDER: PveMethod[] = ["GET", "POST", "PUT", "DELETE"];
/** Width at which a union is broken across lines. */
const UNION_WRAP = 76;

export interface ModelMeta {
  source: string;
  sha256: string;
}

